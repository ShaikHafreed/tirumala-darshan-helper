// Loads the real extension in Chromium and drives the popup. Run: node tests/e2e/popup.e2e.cjs
const { chromium } = require('playwright');
const path = require('path'), os = require('os'), fs = require('fs');
const ext = path.resolve(__dirname, '../..');
let pass = 0, fail = 0;
const ok = (c, m) => { if (c) { pass++; console.log('  ok  ' + m); } else { fail++; console.log('  FAIL ' + m); } };
(async () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'pfh-'));
  const ctx = await chromium.launchPersistentContext(dir, { headless: false, args: [`--disable-extensions-except=${ext}`, `--load-extension=${ext}`, '--headless=new'] });
  let sw = ctx.serviceWorkers()[0]; if (!sw) sw = await ctx.waitForEvent('serviceworker', { timeout: 15000 });
  const id = sw.url().split('/')[2];
  ok(!!id, 'service worker started');
  const pg = await ctx.newPage(); const errs = [];
  pg.on('pageerror', e => errs.push(e.message)); pg.on('console', m => { if (m.type() === 'error') errs.push(m.text()); });
  await pg.goto(`chrome-extension://${id}/popup.html`);
  ok(await pg.isVisible('#disclaimer'), 'disclaimer shown first');
  await pg.click('#disc-accept');
  ok(await pg.isVisible('#auth'), 'auth after disclaimer');
  await pg.click('#tab-signup');
  await pg.fill('#a-name', 'Test User'); await pg.fill('#a-phone', '9876543210'); await pg.fill('#a-pin', '123456'); await pg.fill('#a-pin2', '123456');
  await pg.click('#auth-go');
  await pg.waitForSelector('#app:not([hidden])', { timeout: 20000 });
  ok(true, 'signed up and entered app');
  await pg.click('[data-tab=pilgrims]');
  await pg.click('#add-btn');
  ok(await pg.isHidden('#idnum-wrap'), 'ID number box hidden while ID saving is off');
  await pg.fill('#f-name', 'Asha Rao'); await pg.fill('#f-age', '34'); await pg.click('#save-btn');
  await pg.click('#add-btn'); await pg.fill('#f-name', 'Ravi Rao'); await pg.fill('#f-age', '40'); await pg.selectOption('#f-gender', 'Male'); await pg.click('#save-btn');
  ok((await pg.$$('.pcard')).length === 2, 'two pilgrims listed');
  for (let i = 0; i < 2; i++) await pg.locator('[data-sel]').nth(i).check();
  ok((await pg.textContent('#p-count')).startsWith('2/'), 'two selected');
  // stored data is encrypted
  const raw = await sw.evaluate(() => chrome.storage.local.get(null));
  ok(!JSON.stringify(raw).includes('Asha'), 'names not in plaintext storage');
  // reminder
  await pg.click('[data-tab=alerts]');
  const when = new Date(Date.now() + 26 * 3600e3); when.setHours(10, 0, 0, 0); const p2 = n => String(n).padStart(2, '0');
  await pg.fill('#rem-time', `${when.getFullYear()}-${p2(when.getMonth() + 1)}-${p2(when.getDate())}T${p2(when.getHours())}:${p2(when.getMinutes())}`);
  await pg.click('#rem-set'); await pg.waitForTimeout(800);
  const alarms = await sw.evaluate(() => chrome.alarms.getAll().then(a => a.map(x => x.name)));
  ok(['ttd-r-10', 'ttd-r-5', 'ttd-r-0'].every(n => alarms.includes(n)), 'three alarms armed: ' + alarms.join(','));
  await pg.click('#hc-run'); await pg.waitForTimeout(1500);
  ok((await pg.$$('#hc-list li')).length >= 4, 'health check lists results');
  await pg.click('#ph-qr'); ok(true, 'QR click does not crash (needs phone alerts on)');
  // lock + login
  await pg.click('#lock-btn'); await pg.waitForSelector('#auth:not([hidden])'); ok(true, 'lock returns to login');
  await pg.fill('#a-phone', '9876543210'); await pg.fill('#a-pin', '000000'); await pg.click('#auth-go');
  await pg.waitForTimeout(1500);
  ok((await pg.textContent('#auth-err')).includes('Wrong PIN'), 'wrong PIN rejected');
  await pg.fill('#a-pin', '123456'); await pg.click('#auth-go'); await pg.waitForSelector('#app:not([hidden])');
  ok(true, 'login with right PIN');
  await pg.click('[data-tab=pilgrims]'); await pg.click('#add-btn');
  ok(await pg.isHidden('#pp-wrap'), 'passport block hidden for Aadhaar');
  await pg.selectOption('#f-idtype', '2'); ok(await pg.isVisible('#pp-wrap'), 'passport block shows for Passport');
  await pg.fill('#f-name', 'Nri Person'); await pg.fill('#f-age', '50'); await pg.fill('#f-country', 'USA'); await pg.fill('#f-visatype', 'H1B'); await pg.fill('#f-visaexp', '2030-01-05'); await pg.click('#save-btn');
  ok((await pg.textContent('.ppchip')).includes('USA') && (await pg.textContent('.ppchip')).includes('05/01/2030'), 'passport chip shows country, visa, date');
  await pg.click('[data-tab=settings]'); await pg.click('#s-feedback'); await pg.click('#m-stars span:nth-child(4)');
  ok((await pg.textContent('#m-stars')).startsWith('★★★★☆'), 'feedback stars work'); await pg.fill('#m-msg', 'test'); await pg.click('#sheet .xbtn'); ok(await pg.isHidden('#modal'), 'close button closes the dialog');
  await pg.click('#s-csv'); await pg.fill('#m-in', 'Name,Age,Gender\nMeena Devi,52,Female\nBad,0,Male'); await pg.click('#m-ok'); await pg.waitForTimeout(500);
  ok((await pg.textContent('#toast-text')).includes('Imported 1'), 'csv import adds one pilgrim and skips bad row');
  // practice page fill
  const mock = await ctx.newPage(); await mock.goto(`chrome-extension://${id}/mock.html?tickets=2`);
  await mock.bringToFront();
  await pg.click('[data-tab=home]'); await pg.click('#recheck'); await pg.waitForTimeout(800);
  const cl = await pg.textContent('#checklist');
  console.log('   tabs:', JSON.stringify(await pg.evaluate(async () => (await chrome.tabs.query({currentWindow:true})).map(t=>[t.active,(t.url||'none').slice(-30)]))));
  console.log('   checklist:', cl.replace(/\s+/g,' '));
  ok(/Pilgrim Details form found/.test(cl) && /row\(s\) found/.test(cl), 'checklist sees the practice form');
  await pg.click('#fill-btn');
  await pg.waitForSelector('#m-go', { timeout: 5000 });
  ok((await pg.textContent('#sheet')).includes('Asha Rao'), 'preview lists pilgrims');
  await pg.fill('#pid-0', '123456789012');
  await pg.click('#m-go'); await pg.waitForTimeout(1500);
  const st = await mock.evaluate(() => window.__mockState());
  ok(JSON.stringify(st).includes('Asha Rao') && JSON.stringify(st).includes('Ravi Rao'), 'names filled on the practice page');
  const mk = await mock.evaluate(() => ({ name: document.querySelector('input[name=fname]').style.outline, gender: document.querySelector('input[name=gender]').style.outline }));
  ok(/rgb\(30, 132, 73\)/.test(mk.name), 'filled name box marked green'); ok(/rgb\(242, 140, 40\)/.test(mk.gender), 'gender box highlighted orange');
  ok((await mock.textContent('#ttd-assistant-banner')).includes('Pick Gender'), 'banner says which gender to pick');
  await mock.evaluate(() => window.__ttdPanel([{ name: 'Asha Rao', age: '34', gender: 'Female', idType: '1', idNum: '' }]));
  ok(await mock.evaluate(() => !!document.getElementById('pfh-panel')), 'on-page copy panel shown');
  console.log('   state:', JSON.stringify(st).slice(0, 200));
  ok(errs.length === 0, 'no popup console errors' + (errs.length ? ': ' + errs.join(' | ') : ''));
  await ctx.close(); console.log(`\n${pass} passed, ${fail} failed`); process.exit(fail ? 1 : 0);
})().catch(e => { console.error(e); process.exit(1); });
